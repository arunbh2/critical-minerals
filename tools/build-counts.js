#!/usr/bin/env node
// Computes every headline count from the data and records it in src/data/site/counts.json.
// Pages and AI files read counts from there; no count is ever typed by hand.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const md = (dir) => readdirSync(join(root, 'src/content', dir)).filter((f) => f.endsWith('.md'))
  .filter((f) => !/^draft:\s*true\s*$/m.test(readFileSync(join(root, 'src/content', dir, f), 'utf8').split('\n---')[0]));
const json = (f) => JSON.parse(readFileSync(join(root, 'src/data', f), 'utf8'));
const claims = json('claims.json');
const finance = json('finance.json');
const counts = {
  explainers: md('learn').length,
  minerals: md('minerals').length,
  countries: md('countries').length,
  issues: md('issues').length,
  cases: md('cases').length,
  updates: md('updates').length,
  organisations: json('organisations.json').length,
  policies: json('policies.json').length,
  financeRecords: finance.length,
  openOpportunities: finance.filter((f) => f.recordState === 'open').length,
  sources: json('sources.json').length,
  claimsPublished: claims.filter((c) => c.verification !== 'not-verified').length,
  claimsOriginalChecked: claims.filter((c) => c.verification === 'original-checked').length,
  claimsSecondary: claims.filter((c) => c.verification === 'secondary').length,
  claimsHeldBack: claims.filter((c) => c.verification === 'not-verified').length,
};
mkdirSync(join(root, 'src/data/site'), { recursive: true });
const out = JSON.stringify({ note: 'Generated by tools/build-counts.js. Do not edit.', ...counts }, null, 2) + '\n';
const path = join(root, 'src/data/site/counts.json');
let prev = '';
try { prev = readFileSync(path, 'utf8'); } catch {}
if (process.argv.includes('--check')) {
  if (prev !== out) { console.error('src/data/site/counts.json is out of date. Fix: run `node tools/build-counts.js` and commit the result.'); process.exit(1); }
  console.log('counts.json is current.');
} else {
  writeFileSync(path, out);
  console.log(`Counts: ${Object.entries(counts).map(([k, v]) => `${k}=${v}`).join(', ')}`);
}
